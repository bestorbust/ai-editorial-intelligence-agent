@app.get("/opportunities")
def opportunities(db: Session = Depends(get_db)):

    snapshot = get_latest_snapshot(db)

    if snapshot is None:
        return []

    rows = (
        db.query(Opportunity,Story)
        .join(
            Story,
            Opportunity.story_id == Story.id,
        )
        .filter(
            Story.snapshot_id == snapshot.id
        )
        .order_by(
            Opportunity.score.desc()
        )
        .all()
    )

    return [
        serialize_opportunity(opportunity,story)
        for opportunity,story in rows
    ]


