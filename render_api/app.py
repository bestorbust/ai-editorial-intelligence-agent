def serialize_topic(topic: Topic):
    return {
        "id": topic.id,
        "title": topic.title,
        "summary": topic.summary,
        "source": topic.source,
        "source_url": topic.source_url,
        "category": topic.category,
        "language": topic.language,
        "country": topic.country,
        "keywords": topic.keywords or [],
        "entities": topic.entities or [],
        "trend_score": topic.trend_score,
        "confidence_score": topic.confidence_score,
        "status": topic.status,
        "discovered_at": topic.discovered_at,
        "updated_at": topic.updated_at,
    }


def serialize_story(story: Story):
    return {
        "id": story.id,
        "snapshot_id": story.snapshot_id,
        "title": story.title,
        "summary": story.summary,
        "keywords": story.keywords or [],
        "category": story.category,
        "editorial_score": story.editorial_score,
        "topic_count": story.topic_count,
    }


def serialize_opportunity(
    opportunity: Opportunity,
    story: Story,
):
    """
    Keep the API response compatible with the frontend.

    The database stores the detailed opportunity information
    inside the JSON explanation field.
    """

    explanation = opportunity.explanation or {}

    if not isinstance(explanation, dict):
        explanation = {}

    return {
        "id": opportunity.id,
        "story_id": opportunity.story_id,

        # Frontend-compatible fields
        "headline": opportunity.headline,
        "score": opportunity.score,

        "explanation": {
            "summary": explanation.get("summary", ""),
            "strengths": explanation.get("strengths", []),
            "weaknesses": explanation.get("weaknesses", []),
            "recommended_formats": explanation.get(
                "recommended_formats",
                [],
            ),
            "sources": explanation.get("sources", []),
            "scores": explanation.get("scores", {}),
            "keywords": explanation.get("keywords", []),
            "entities": explanation.get("entities", []),
        },

        # Convenience fields for filtering/searching
        "category": explanation.get("category"),
        "keywords": explanation.get("keywords", []),
        "entities": explanation.get("entities", []),
    }


