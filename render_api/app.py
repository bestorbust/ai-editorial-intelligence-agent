@app.get("/stories")
def stories(db: Session = Depends(get_db)):

    snapshot = get_latest_snapshot(db)

    if snapshot is None:
        return []

    rows = (
        db.query(Story)
        .filter(
            Story.snapshot_id == snapshot.id
        )
        .order_by(
            Story.editorial_score.desc()
        )
        .all()
    )

    return [
        serialize_story(story)
        for story in rows
    ]


