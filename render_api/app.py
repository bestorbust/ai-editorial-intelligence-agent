@app.get("/topics")
def topics(db: Session = Depends(get_db)):

    snapshot = get_latest_snapshot(db)

    if snapshot is None:
        return []

    rows = (
        db.query(Topic)
        .join(
            TopicSnapshot,
            Topic.id == TopicSnapshot.topic_id,
        )
        .filter(
            TopicSnapshot.snapshot_id == snapshot.id
        )
        .order_by(Topic.id.desc())
        .all()
    )

    return [
        serialize_topic(topic)
        for topic in rows
    ]


